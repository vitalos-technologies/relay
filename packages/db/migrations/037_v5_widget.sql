-- V5 stream WID: marketing support widget (brief docs/queue/03h_V5_PROMPT.md §9–10). Additive.
-- Contracts: packages/core/src/contracts/v5-widget.ts. Services: packages/services/src/support/widget*.ts.
-- The widget talks to the EXISTING V4 support service (support_tickets / support_messages / support_activity): there is no
-- second ticket system. This migration only adds what anonymous visitors need:
--  * widget_visitors: an unguessable visitor identity (random uuid, never derived from input). support_tickets.visitor_id
--    (already present since 034, requester_kind='visitor') now references it. The contact email a visitor types is stored
--    as typed and is NEVER proof of identity: it grants nothing until verified with a one-time code/link.
--  * widget_sessions: the browser's access to a visitor identity — an opaque random token in an HttpOnly cookie, only its
--    SHA-256 stored; absolute + idle expiry; its own CSRF token. verified_email is set ONLY by the one-time verification
--    flow and is what lets a second device see conversations started with that contact email. Nothing here ever links a
--    visitor to a user account or workspace (no automatic merge by email).
--  * widget_verifications: one-time codes / links (hashes only; secrets are generated by the worker at send time, so no
--    plaintext secret is ever persisted, not even in the outbox payload). Attempt-limited and short-lived.
--  * widget_emails: durable delivery log for visitor emails (verification codes, content-free "Relay replied" notices),
--    deduplicated per message / verification, with the email outcome kept separate from the message itself.
--  * widget_submissions: client-generated submission ids → the message they created (deduplicated submission, also for a
--    first message retried after a lost response).
--  * widget_ticket_reads: per-visitor read state (unread badge) — visitors are not users, so support_ticket_reads can't hold it.
--  * support_attachments.visitor_id: visitor-owned uploads through the same quarantine pipeline.
--  * category 'general' ("General question") for pre-sales / general widget messages.
-- Retention: sessions are deleted 30 days after they end, verifications after 2 days, visitors with no ticket and no live
-- session after 30 days (worker sweep, support/widget-sweeps.ts). Visitor tickets follow the V4 ticket retention.
-- Rollback: ALTER TABLE support_attachments DROP COLUMN visitor_id; ALTER TABLE support_tickets DROP CONSTRAINT
--   support_tickets_visitor_fk; DROP TABLE widget_ticket_reads, widget_submissions, widget_emails, widget_verifications,
--   widget_sessions, widget_visitors; restore the category checks without 'general' (after re-categorising those rows).

CREATE TABLE widget_visitors (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name              text CHECK (name IS NULL OR length(name) BETWEEN 1 AND 120),
  contact_email     citext CHECK (contact_email IS NULL OR length(contact_email) <= 254),
  -- Set when this identity's contact email was confirmed with a one-time code/link (informational for staff).
  email_verified_at timestamptz,
  -- Abuse control: staff can block a visitor identity; blocked visitors cannot send.
  blocked_at        timestamptz,
  blocked_by        uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  last_seen_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX widget_visitors_email_idx ON widget_visitors (contact_email) WHERE contact_email IS NOT NULL;

CREATE TABLE widget_sessions (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  visitor_id      uuid NOT NULL REFERENCES widget_visitors(id) ON DELETE CASCADE,
  token_hash      bytea NOT NULL UNIQUE,
  csrf_token      text NOT NULL CHECK (length(csrf_token) BETWEEN 20 AND 100),
  verified_email  citext CHECK (verified_email IS NULL OR length(verified_email) <= 254),
  verified_at     timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  last_seen_at    timestamptz NOT NULL DEFAULT now(),
  expires_at      timestamptz NOT NULL,
  revoked_at      timestamptz,
  revoked_reason  text CHECK (revoked_reason IS NULL OR length(revoked_reason) <= 40),
  CHECK ((verified_email IS NULL) = (verified_at IS NULL))
);
CREATE INDEX widget_sessions_visitor_idx ON widget_sessions (visitor_id);
CREATE INDEX widget_sessions_expiry_idx ON widget_sessions (expires_at);

CREATE TABLE widget_verifications (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- 'access': a browser asked to see conversations for an email (code + link to that browser's session);
  -- 'reply_link': the one-time link inside a "Relay replied" email (opens that conversation on any device once).
  purpose     text NOT NULL CHECK (purpose IN ('access','reply_link')),
  email       citext NOT NULL CHECK (length(email) <= 254),
  session_id  uuid REFERENCES widget_sessions(id) ON DELETE CASCADE,
  ticket_id   uuid REFERENCES support_tickets(id) ON DELETE CASCADE,
  code_hash   bytea,
  token_hash  bytea UNIQUE,
  attempts    integer NOT NULL DEFAULT 0,
  state       text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','issued','used','expired','locked','undeliverable')),
  created_at  timestamptz NOT NULL DEFAULT now(),
  issued_at   timestamptz,
  expires_at  timestamptz NOT NULL,
  used_at     timestamptz,
  used_by_session uuid REFERENCES widget_sessions(id) ON DELETE SET NULL,
  CHECK (purpose <> 'access' OR session_id IS NOT NULL),
  CHECK (purpose <> 'reply_link' OR ticket_id IS NOT NULL)
);
CREATE INDEX widget_verifications_session_idx ON widget_verifications (session_id, created_at DESC) WHERE session_id IS NOT NULL;
CREATE INDEX widget_verifications_email_idx ON widget_verifications (email, created_at DESC);

CREATE TABLE widget_emails (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  kind             text NOT NULL CHECK (kind IN ('verification','reply')),
  to_email         citext NOT NULL CHECK (length(to_email) <= 254),
  ticket_id        uuid REFERENCES support_tickets(id) ON DELETE CASCADE,
  message_id       uuid REFERENCES support_messages(id) ON DELETE CASCADE,
  verification_id  uuid REFERENCES widget_verifications(id) ON DELETE CASCADE,
  dedupe_key       text NOT NULL UNIQUE CHECK (length(dedupe_key) <= 120),
  state            text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','sent','failed','not_configured','skipped')),
  attempts         integer NOT NULL DEFAULT 0,
  error            text CHECK (error IS NULL OR length(error) <= 200),
  next_attempt_at  timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now(),
  sent_at          timestamptz
);
CREATE INDEX widget_emails_retry_idx ON widget_emails (next_attempt_at) WHERE state = 'pending';
CREATE INDEX widget_emails_message_idx ON widget_emails (message_id) WHERE message_id IS NOT NULL;

CREATE TABLE widget_submissions (
  client_id     uuid PRIMARY KEY,
  visitor_id    uuid NOT NULL REFERENCES widget_visitors(id) ON DELETE CASCADE,
  ticket_id     uuid NOT NULL REFERENCES support_tickets(id) ON DELETE CASCADE,
  message_id    uuid NOT NULL REFERENCES support_messages(id) ON DELETE CASCADE,
  request_hash  text NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE widget_ticket_reads (
  ticket_id     uuid NOT NULL REFERENCES support_tickets(id) ON DELETE CASCADE,
  visitor_id    uuid NOT NULL REFERENCES widget_visitors(id) ON DELETE CASCADE,
  last_read_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (ticket_id, visitor_id)
);

ALTER TABLE support_tickets ADD CONSTRAINT support_tickets_visitor_fk FOREIGN KEY (visitor_id) REFERENCES widget_visitors(id);
CREATE INDEX support_tickets_visitor_email_idx ON support_tickets (visitor_email) WHERE requester_kind = 'visitor';

ALTER TABLE support_attachments ADD COLUMN visitor_id uuid REFERENCES widget_visitors(id) ON DELETE CASCADE;
ALTER TABLE support_attachments ADD CONSTRAINT support_attachments_visitor_owner_check CHECK (owner_kind <> 'visitor' OR visitor_id IS NOT NULL);

ALTER TABLE support_tickets DROP CONSTRAINT IF EXISTS support_tickets_category_check;
ALTER TABLE support_tickets ADD CONSTRAINT support_tickets_category_check
  CHECK (category IN ('general','account_access','billing','publishing','connections','analytics','technical','feature_request','security'));
ALTER TABLE support_saved_replies DROP CONSTRAINT IF EXISTS support_saved_replies_category_check;
ALTER TABLE support_saved_replies ADD CONSTRAINT support_saved_replies_category_check
  CHECK (category IS NULL OR category IN ('general','account_access','billing','publishing','connections','analytics','technical','feature_request','security'));
