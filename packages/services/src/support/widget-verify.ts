// V5 WID — cross-device access for widget visitors via a one-time emailed code / link, and visitor email delivery.
// Security model (docs/v5/SUPPORT_WIDGET_SECURITY_AND_OPERATION.md):
//  * Typing an email proves nothing. Access to conversations started with a contact email requires proving control of
//    that mailbox: a 6-digit code (attempt-limited) or a one-time link, both expiring after WIDGET_VERIFY_TTL_MINUTES.
//  * Codes are only emailed when that address has widget conversations, so the widget can't be used to send mail to
//    arbitrary inboxes; the API answers identically either way (no account/ticket enumeration).
//  * Secrets are generated by the WORKER at send time and only their SHA-256 is stored — never plaintext, not even in the
//    outbox payload. A retried send issues fresh secrets (older ones stop working).
//  * Links use the URL fragment (/#support-verify=…): never sent to the server on page load or in Referer headers, and a
//    mail scanner prefetching the link consumes nothing — the widget asks the person to confirm, then POSTs the token.
//  * Success sets widget_sessions.verified_email for THAT browser session only. No user account or workspace is ever
//    linked or merged; signed-in requests keep using account context.
//  * "Relay replied" emails to visitors are content-free (reference + one-time link), deduplicated per staff message,
//    and their outcome is recorded separately from the reply (widget_emails), shown to staff under the reply.
import { randomInt, timingSafeEqual } from 'node:crypto';
import { z } from 'zod';
import { AppError, BRAND } from '@social-lite/core';
import {
  WIDGET_REPLY_LINK_TTL_HOURS, WIDGET_VERIFY_MAX_ATTEMPTS, WIDGET_VERIFY_TTL_MINUTES, type WidgetConversationSummary,
} from '@social-lite/core/contracts/v5-widget';
import { getPool, many, maybeOne, one, withTx, type Queryable } from '@social-lite/db';
import { randomToken, sha256 } from '../auth/session.js';
import { config } from '../config.js';
import { mailer, sendMail, type MailMessage } from '../email.js';
import { enforceRateLimit } from '../ratelimit.js';
import { writeOutbox } from '../outbox.js';
import { isUuid } from '../tenancy.js';
import { log } from '../log.js';
import { createVisitor, createWidgetSession, type WidgetSession } from './widget-session.js';
import { visitorConversations, type WidgetCaller } from './widget.js';

export const VERIFY_RATES = {
  requestPerIp: { capacity: 5, refillPerSecond: 5 / 3600 },
  requestPerEmail: { capacity: 3, refillPerSecond: 3 / 3600 },
  confirmPerIp: { capacity: 20, refillPerSecond: 20 / 3600 },
} as const;
export const WIDGET_EMAIL_MAX_ATTEMPTS = 3;

type Transport = (m: MailMessage) => Promise<boolean>;
let testTransport: Transport | null = null;
/** Tests only: capture visitor emails (codes/links) instead of SMTP. */
export function setWidgetMailTransportForTests(t: Transport | null): void { testTransport = t; }

const emailSchema = z.object({ email: z.email({ message: 'Enter the email you used' }).max(254) }).strict();

export interface VerifyRequestResult { ok: true; expires_in_minutes: number; newSession: { token: string; session: WidgetSession } | null }

/** Ask for a one-time code/link for an email. Same answer whether or not that email has conversations. */
export async function requestVerification(c: WidgetCaller, raw: unknown, db: Queryable = getPool()): Promise<VerifyRequestResult> {
  const { email } = emailSchema.parse(raw);
  await enforceRateLimit('widgetVerifyIp', c.ip, VERIFY_RATES.requestPerIp);
  await enforceRateLimit('widgetVerifyEmail', email.toLowerCase(), VERIFY_RATES.requestPerEmail);
  if (c.visitor?.visitor.blocked) throw new AppError('forbidden', 'This browser can’t use the chat. Email us instead.');
  return withTx(async (tx) => {
    let newSession: VerifyRequestResult['newSession'] = null;
    let sessionId = c.visitor?.id ?? null;
    if (!sessionId) {
      newSession = await createWidgetSession(tx, await createVisitor(tx));
      sessionId = newSession.session.id;
    }
    await tx.query(`UPDATE widget_verifications SET state='expired' WHERE session_id=$1 AND purpose='access' AND state IN ('pending','issued')`, [sessionId]);
    const has = await maybeOne(tx, `SELECT 1 FROM support_tickets WHERE requester_kind='visitor' AND visitor_email=$1::citext LIMIT 1`, [email]);
    const v = await one<{ id: string }>(tx,
      `INSERT INTO widget_verifications(purpose, email, session_id, state, expires_at) VALUES ('access', $1, $2, $3, now() + make_interval(mins => $4)) RETURNING id`,
      [email, sessionId, has ? 'pending' : 'undeliverable', WIDGET_VERIFY_TTL_MINUTES]);
    if (has) await writeOutbox(tx, { workspaceId: null, aggregateType: 'widget_verification', aggregateId: v.id, eventType: 'support.widget_verification', payload: {} });
    return { ok: true as const, expires_in_minutes: WIDGET_VERIFY_TTL_MINUTES, newSession };
  });
}

const confirmSchema = z.union([
  z.object({ code: z.string().trim().regex(/^\d{6}$/, 'Enter the 6-digit code') }).strict(),
  z.object({ token: z.string().trim().min(20).max(200) }).strict(),
]);

export interface VerifyConfirmResult {
  verified_email: string; conversations: WidgetConversationSummary[]; open_reference: string | null;
  newSession: { token: string; session: WidgetSession } | null;
}

/** Confirm with the emailed code (same browser session) or the one-time link token (any browser). */
export async function confirmVerification(c: WidgetCaller, raw: unknown, db: Queryable = getPool()): Promise<VerifyConfirmResult> {
  const input = confirmSchema.parse(raw);
  await enforceRateLimit('widgetConfirmIp', c.ip, VERIFY_RATES.confirmPerIp);
  if (c.visitor?.visitor.blocked) throw new AppError('forbidden', 'This browser can’t use the chat. Email us instead.');
  // Code path: check (and count a failed attempt) BEFORE the transaction, atomically, so a wrong code is always counted.
  let codeRowId: string | null = null;
  if ('code' in input) {
    if (!c.visitor) throw new AppError('invalid_state', 'Ask for a new code.');
    const cand = await maybeOne<{ id: string; code_hash: Buffer | null; expires_at: Date; state: string }>(db,
      `SELECT id, code_hash, expires_at, state FROM widget_verifications WHERE session_id=$1 AND purpose='access' AND state IN ('issued','locked')
        ORDER BY created_at DESC LIMIT 1`, [c.visitor.id]);
    if (!cand || cand.state === 'locked' || cand.expires_at < new Date() || !cand.code_hash) throw new AppError('invalid_state', 'That code has expired or is used up. Ask for a new one.');
    if (!(cand.code_hash.length === 32 && timingSafeEqual(cand.code_hash, sha256(input.code)))) {
      const r = await maybeOne<{ attempts: number }>(db,
        `UPDATE widget_verifications SET attempts=attempts+1, state=CASE WHEN attempts+1 >= $2 THEN 'locked' ELSE state END WHERE id=$1 AND state='issued' RETURNING attempts`,
        [cand.id, WIDGET_VERIFY_MAX_ATTEMPTS]);
      const left = WIDGET_VERIFY_MAX_ATTEMPTS - (r?.attempts ?? WIDGET_VERIFY_MAX_ATTEMPTS);
      throw new AppError('validation_failed', left > 0 ? `That code didn’t match. ${left} ${left === 1 ? 'try' : 'tries'} left.` : 'Too many tries. Ask for a new code.', { code: 'mismatch' });
    }
    codeRowId = cand.id;
  }
  const res = await withTx(async (tx) => {
    type VRow = { id: string; purpose: 'access' | 'reply_link'; email: string; ticket_id: string | null; expires_at: Date; state: string };
    const row = codeRowId
      ? await maybeOne<VRow>(tx, `SELECT id, purpose, email::text AS email, ticket_id, expires_at, state FROM widget_verifications WHERE id=$1 AND state='issued' FOR UPDATE`, [codeRowId])
      : await maybeOne<VRow>(tx, `SELECT id, purpose, email::text AS email, ticket_id, expires_at, state FROM widget_verifications WHERE token_hash=$1 AND state='issued' FOR UPDATE`,
        [sha256((input as { token: string }).token)]);
    if (!row || row.expires_at < new Date()) {
      throw new AppError('invalid_state', codeRowId ? 'That code has expired or is used up. Ask for a new one.' : 'This link has expired or was already used. Ask for a new code in the chat.');
    }
    let newSession: VerifyConfirmResult['newSession'] = null;
    let session = c.visitor;
    if (!session) {
      newSession = await createWidgetSession(tx, await createVisitor(tx), { email: row.email });
      session = newSession.session;
    } else {
      await tx.query(`UPDATE widget_sessions SET verified_email=$2, verified_at=now() WHERE id=$1`, [session.id, row.email]);
      session = { ...session, verifiedEmail: row.email };
    }
    await tx.query(`UPDATE widget_verifications SET state='used', used_at=now(), used_by_session=$2 WHERE id=$1`, [row.id, session.id]);
    await tx.query(`UPDATE widget_visitors SET email_verified_at=coalesce(email_verified_at, now()) WHERE contact_email=$1::citext`, [row.email]);
    const ref = row.ticket_id ? (await maybeOne<{ reference: string }>(tx, `SELECT reference FROM support_tickets WHERE id=$1`, [row.ticket_id]))?.reference ?? null : null;
    return { session, newSession, email: row.email, ref };
  });
  return { verified_email: res.email, conversations: await visitorConversations(db, res.session), open_reference: res.ref, newSession: res.newSession };
}

// ------------------------------------------------------------------ worker: visitor emails
/** support.widget_verification → queue the code email (deduplicated per verification). */
export async function handleWidgetVerification(db: Queryable, verificationId: unknown): Promise<void> {
  if (!isUuid(verificationId)) return;
  const v = await maybeOne<{ email: string; state: string }>(db, `SELECT email::text AS email, state FROM widget_verifications WHERE id=$1`, [verificationId]);
  if (!v || v.state !== 'pending') return;
  const e = await maybeOne<{ id: string }>(db,
    `INSERT INTO widget_emails(kind, to_email, verification_id, dedupe_key) VALUES ('verification', $1, $2, $3) ON CONFLICT (dedupe_key) DO NOTHING RETURNING id`,
    [v.email, verificationId, `verify:${verificationId}`]);
  if (e) await deliverWidgetEmail(db, e.id);
}

/** Staff public reply on a visitor ticket → content-free "Relay replied" email to the contact address (once per message). */
export async function queueVisitorReplyEmail(db: Queryable, t: { id: string; reference: string }, messageId: string): Promise<void> {
  const row = await maybeOne<{ visitor_email: string | null }>(db, `SELECT visitor_email::text AS visitor_email FROM support_tickets WHERE id=$1 AND requester_kind='visitor'`, [t.id]);
  if (!row?.visitor_email) return;
  const e = await maybeOne<{ id: string }>(db,
    `INSERT INTO widget_emails(kind, to_email, ticket_id, message_id, dedupe_key) VALUES ('reply', $1, $2, $3, $4) ON CONFLICT (dedupe_key) DO NOTHING RETURNING id`,
    [row.visitor_email, t.id, messageId, `support:msg:${messageId}`]);
  if (e) await deliverWidgetEmail(db, e.id);
}

const link = (token: string) => `${config().APP_BASE_URL.replace(/\/$/, '')}/#support-verify=${token}`;

/** Send one queued visitor email (fresh secrets each attempt). Idempotent on state; retries back off (sweep). */
export async function deliverWidgetEmail(db: Queryable, emailId: string): Promise<'sent' | 'failed' | 'not_configured' | 'skipped' | 'retry'> {
  const e = await maybeOne<{ id: string; kind: 'verification' | 'reply'; to_email: string; ticket_id: string | null; message_id: string | null; verification_id: string | null; state: string; attempts: number }>(db,
    `SELECT id, kind, to_email::text AS to_email, ticket_id, message_id, verification_id, state, attempts FROM widget_emails WHERE id=$1`, [emailId]);
  if (!e || e.state !== 'pending') return 'skipped';
  const skip = async (why: string) => { await db.query(`UPDATE widget_emails SET state='skipped', error=$2 WHERE id=$1`, [e.id, why]); return 'skipped' as const; };
  const transport: Transport | null = testTransport ?? (mailer() ? (m) => sendMail(m) : null);
  if (!transport) {
    await db.query(`UPDATE widget_emails SET state='not_configured', error='smtp_not_configured' WHERE id=$1`, [e.id]);
    if (e.verification_id) await db.query(`UPDATE widget_verifications SET state='undeliverable' WHERE id=$1 AND state='pending'`, [e.verification_id]);
    return 'not_configured';
  }
  let mail: MailMessage;
  if (e.kind === 'verification') {
    const v = await maybeOne<{ id: string; state: string; expires_at: Date }>(db, `SELECT id, state, expires_at FROM widget_verifications WHERE id=$1`, [e.verification_id]);
    if (!v || !['pending', 'issued'].includes(v.state) || v.expires_at < new Date()) return skip('verification_inactive');
    const code = String(randomInt(0, 1_000_000)).padStart(6, '0');
    const token = randomToken(32);
    await db.query(`UPDATE widget_verifications SET code_hash=$2, token_hash=$3, state='issued', issued_at=now(), attempts=0 WHERE id=$1`, [v.id, sha256(code), sha256(token)]);
    mail = {
      to: e.to_email,
      subject: `Your ${BRAND.name} support code`,
      text: [
        `Your code: ${code}`,
        '',
        `Enter it in the ${BRAND.name} support chat to see your conversations in that browser, or open this link on the device you want to use:`,
        link(token),
        '',
        `The code and the link work once and expire in ${WIDGET_VERIFY_TTL_MINUTES} minutes.`,
        'If you didn’t ask for this, ignore this email — nobody can open your conversations without it.',
      ].join('\n'),
    };
  } else {
    const t = await maybeOne<{ id: string; reference: string; visitor_email: string | null }>(db,
      `SELECT t.id, t.reference, t.visitor_email::text AS visitor_email FROM support_tickets t JOIN support_messages m ON m.ticket_id=t.id AND m.id=$2 AND m.author_kind='staff'
        WHERE t.id=$1 AND t.requester_kind='visitor'`, [e.ticket_id, e.message_id]);
    if (!t || !t.visitor_email || t.visitor_email.toLowerCase() !== e.to_email.toLowerCase()) return skip('recipient_changed');
    const token = randomToken(32);
    await db.query(`INSERT INTO widget_verifications(purpose, email, ticket_id, token_hash, state, issued_at, expires_at)
                    VALUES ('reply_link', $1, $2, $3, 'issued', now(), now() + make_interval(hours => $4))`, [t.visitor_email, t.id, sha256(token), WIDGET_REPLY_LINK_TTL_HOURS]);
    mail = {
      to: e.to_email,
      subject: `${BRAND.name} support replied · ${t.reference}`,
      text: [
        `${BRAND.name} support replied to your message (${t.reference}).`,
        '',
        `Open the conversation: ${link(token)}`,
        `This link works once and expires in ${WIDGET_REPLY_LINK_TTL_HOURS} hours. You can also open the chat on the device you used to write to us.`,
        '',
        `You received this because this address was given as the contact email in the ${BRAND.name} support chat. If that wasn’t you, ignore this email.`,
      ].join('\n'),
    };
  }
  const ok = await transport(mail).catch(() => false);
  if (ok) {
    await db.query(`UPDATE widget_emails SET state='sent', sent_at=now(), attempts=attempts+1, error=NULL, next_attempt_at=NULL WHERE id=$1`, [e.id]);
    return 'sent';
  }
  const attempts = e.attempts + 1;
  if (attempts >= WIDGET_EMAIL_MAX_ATTEMPTS) {
    await db.query(`UPDATE widget_emails SET state='failed', attempts=$2, error='smtp_rejected', next_attempt_at=NULL WHERE id=$1`, [e.id, attempts]);
    return 'failed';
  }
  await db.query(`UPDATE widget_emails SET attempts=$2, error='smtp_rejected', next_attempt_at=now() + make_interval(mins => $3) WHERE id=$1`, [e.id, attempts, 5 * attempts]);
  return 'retry';
}

/** Worker sweep: retry visitor emails whose back-off has elapsed. */
export async function retryWidgetEmails(db: Queryable = getPool(), limit = 50): Promise<number> {
  const rows = await many<{ id: string }>(db, `SELECT id FROM widget_emails WHERE state='pending' AND next_attempt_at IS NOT NULL AND next_attempt_at <= now() ORDER BY next_attempt_at LIMIT $1`, [limit]);
  let n = 0;
  for (const r of rows) {
    try { if ((await deliverWidgetEmail(db, r.id)) === 'sent') n++; } catch (err) { log.warn('widget_email_retry_failed', { err: err as Error }); }
  }
  return n;
}

/** Staff view: email outcome per staff reply on visitor tickets (merged into deliverySummary). */
export async function visitorEmailSummary(db: Queryable, messageIds: string[]): Promise<Map<string, string>> {
  const out = new Map<string, string>();
  if (!messageIds.length) return out;
  const rows = await many<{ message_id: string; state: string }>(db, `SELECT message_id, state FROM widget_emails WHERE kind='reply' AND message_id = ANY($1::uuid[])`, [messageIds]);
  for (const r of rows) out.set(r.message_id, r.state);
  return out;
}
